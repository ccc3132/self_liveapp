-- 전자결재(직접 개발, 공통컴포넌트에 없는 모듈). messenger(V13)의 MSGR_ 접두사 선례와
-- 동일하게 COMTN 접두사를 쓰지 않고 자체 접두사(APV_)를 쓴다.
-- JSON 컬럼은 JSONB가 아니라 TEXT로 둔다: 애플리케이션(Jackson)에서 이미 검증하므로
-- DB 레벨 JSON 유효성 체크는 중복이고, TEXT면 MyBatis에서 캐스팅 이슈가 없다.

-- 1) 관리자가 만드는 결재 양식 템플릿. 필드 구성은 EAV가 아니라 순서가 있는 JSON
--    배열로 저장한다(드래그앤드롭 빌더가 그대로 만들어내는 구조).
CREATE TABLE APV_TEMPLATE
(
    TEMPLATE_ID         BIGSERIAL PRIMARY KEY,
    TEMPLATE_NM         VARCHAR(100)  NOT NULL,
    DESCRIPTION         VARCHAR(500)  NULL,
    FIELD_SCHEMA        TEXT          NOT NULL,
    FILE_ATCH_POSBL_AT  CHAR(1)       NOT NULL DEFAULT 'N',
    USE_AT              CHAR(1)       NOT NULL DEFAULT 'Y',
    FRST_REGISTER_ID    VARCHAR(20)   NOT NULL,
    FRST_REGIST_PNTTM   TIMESTAMP     NOT NULL DEFAULT NOW(),
    LAST_UPDUSR_ID      VARCHAR(20)   NULL,
    LAST_UPDATE_PNTTM   TIMESTAMP     NULL
);

CREATE INDEX APV_TEMPLATE_i01 ON APV_TEMPLATE (USE_AT);

-- 2) 신청(상신) 문서. SCHEMA_SNAPSHOT은 제출 시점의 FIELD_SCHEMA를 그대로 얼려서
--    보관한다 — 템플릿이 나중에 수정/삭제되어도 과거 제출물의 렌더링이 바뀌지 않는다.
CREATE TABLE APV_SUBMISSION
(
    SUBMISSION_ID       BIGSERIAL PRIMARY KEY,
    TEMPLATE_ID         BIGINT        NOT NULL REFERENCES APV_TEMPLATE(TEMPLATE_ID),
    TEMPLATE_NM         VARCHAR(100)  NOT NULL,
    SCHEMA_SNAPSHOT     TEXT          NOT NULL,
    FIELD_VALUES        TEXT          NOT NULL,
    TITLE               VARCHAR(200)  NOT NULL,
    REQUESTER_ID        VARCHAR(20)   NOT NULL,
    REQUESTER_NM        VARCHAR(60)   NOT NULL,
    ATCH_FILE_ID        VARCHAR(20)   NULL,
    STATUS              VARCHAR(10)   NOT NULL DEFAULT '진행중',
    CURRENT_STEP_ORDER  INT           NOT NULL DEFAULT 1,
    SUBMITTED_AT        TIMESTAMP     NOT NULL DEFAULT NOW(),
    COMPLETED_AT        TIMESTAMP     NULL
);

CREATE INDEX APV_SUBMISSION_i01 ON APV_SUBMISSION (REQUESTER_ID);
CREATE INDEX APV_SUBMISSION_i02 ON APV_SUBMISSION (STATUS);

-- 3) 순차 결재선. 한 제출문서에 N개 행(step_order 1..N), 요청자가 상신 시 고른 순서.
CREATE TABLE APV_LINE
(
    LINE_ID         BIGSERIAL PRIMARY KEY,
    SUBMISSION_ID   BIGINT       NOT NULL REFERENCES APV_SUBMISSION(SUBMISSION_ID) ON DELETE CASCADE,
    STEP_ORDER      INT          NOT NULL,
    APPROVER_ID     VARCHAR(20)  NOT NULL,
    APPROVER_NM     VARCHAR(60)  NOT NULL,
    STATUS          VARCHAR(10)  NOT NULL DEFAULT '대기',
    COMMENT_CN      VARCHAR(1000) NULL,
    PROCESSED_AT    TIMESTAMP    NULL,
    UNIQUE (SUBMISSION_ID, STEP_ORDER)
);

CREATE INDEX APV_LINE_i01 ON APV_LINE (APPROVER_ID, STATUS);
CREATE INDEX APV_LINE_i02 ON APV_LINE (SUBMISSION_ID);
