-- 메신저(직접 개발, 공통컴포넌트에 없는 모듈). 1:1 대화만 지원하는 최소 범위.
-- 보낸이/받는이는 ESNTL_ID(uniqId)로 식별하고, 화면에 바로 쓸 수 있게 이름을 보낼 때 함께 저장한다
-- (업무사용자/일반회원 테이블이 갈려 있어 매번 조인하기보다 단순하게 비정규화).
CREATE TABLE MSGR_MESSAGE
(
	MSG_ID         BIGSERIAL PRIMARY KEY,
	SENDER_ID      VARCHAR(20) NOT NULL,
	SENDER_NM      VARCHAR(50) NOT NULL,
	RECEIVER_ID    VARCHAR(20) NOT NULL,
	RECEIVER_NM    VARCHAR(50) NOT NULL,
	CONTENT        VARCHAR(2000) NOT NULL,
	SENT_AT        TIMESTAMP NOT NULL DEFAULT NOW(),
	READ_AT        TIMESTAMP NULL
);

CREATE INDEX MSGR_MESSAGE_i01 ON MSGR_MESSAGE (SENDER_ID, RECEIVER_ID);
CREATE INDEX MSGR_MESSAGE_i02 ON MSGR_MESSAGE (RECEIVER_ID, SENDER_ID);
